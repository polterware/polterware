// Package projection renders the files Polterware writes into checkouts: one
// Markdown file per ADR under docs/adr/ and one generated block in AGENTS.md.
// The store stays the source of truth; nothing here reads a checkout back.
// It is pure so the export composition only moves bytes.
package projection

import (
	"fmt"
	"regexp"
	"slices"
	"strings"

	"github.com/polterware/polterware/backend/domains/atlas"
	"github.com/polterware/polterware/backend/domains/polter"
	"github.com/polterware/polterware/backend/domains/work"
)

const (
	// BlockBegin and BlockEnd delimit the generated AGENTS.md block. Export
	// replaces what lies between them and leaves the rest of the file alone.
	BlockBegin = "<!-- polterware:begin generated -->"
	BlockEnd   = "<!-- polterware:end generated -->"

	// ADRDir is where ADR projections go, relative to a checkout.
	ADRDir = "docs/adr"
	// AgentsFile is the agent instructions file, relative to a checkout.
	AgentsFile = "AGENTS.md"
)

// ADR is one decision record from the project store.
type ADR struct {
	ID     string
	Title  string
	Body   string
	Status string
}

var (
	adrMarker   = regexp.MustCompile(`^<!-- polterware:adr (\S+) `)
	adrFileName = regexp.MustCompile(`^(\d{4})-[^/]*\.md$`)
	titlePrefix = regexp.MustCompile(`(?i)^\s*adr[\s\-_]*\d+\s*[:.\-–—]?\s*`)
)

const maxSlugRunes = 60

// Govern assigns each ADR to the checkouts it governs: the repo of every
// active node that cites it in decisions:. An ADR no active node cites
// governs the project root (""). The result is keyed by checkout name.
func Govern(nodes []atlas.Node, adrs []ADR) map[string][]ADR {
	out := map[string][]ADR{}
	for _, adr := range adrs {
		repos := map[string]bool{}
		for _, node := range nodes {
			if node.Status == atlas.NodeRemoved {
				continue
			}
			for _, ref := range node.Decisions {
				if Cites(ref, adr) {
					repos[node.Repo] = true
				}
			}
		}
		if len(repos) == 0 {
			repos[""] = true
		}
		for repo := range repos {
			out[repo] = append(out[repo], adr)
		}
	}
	for repo := range out {
		sortADRs(out[repo])
	}
	return out
}

// Cites reports whether a decisions: entry names adr, by id or ADR number.
func Cites(ref string, adr ADR) bool {
	return polter.CitesDecision(ref, adr.ID, adr.Title)
}

// ADRFile returns the file name under docs/adr/ and the projected content.
// ok is false when the title carries no ADR number.
func ADRFile(adr ADR) (name, content string, ok bool) {
	number, ok := polter.ParseADRNumber(adr.Title)
	if !ok {
		return "", "", false
	}
	slug := slugify(titlePrefix.ReplaceAllString(adr.Title, ""))
	if slug == "" {
		slug = "decision"
	}
	name = fmt.Sprintf("%04d-%s.md", number, slug)

	var b strings.Builder
	fmt.Fprintf(&b, "<!-- polterware:adr %s generated by polterware export; edits here are replaced on the next export -->\n", adr.ID)
	body := strings.TrimSpace(adr.Body)
	if !strings.HasPrefix(body, "# ") {
		fmt.Fprintf(&b, "# %s\n\n", adr.Title)
	} else if title, rest, found := strings.Cut(body, "\n"); found {
		b.WriteString(title + "\n\n")
		body = strings.TrimSpace(rest)
	} else {
		b.WriteString(body + "\n\n")
		body = ""
	}
	if adr.Status != "" {
		fmt.Fprintf(&b, "Lifecycle status: %s\n\n", adr.Status)
	}
	if body != "" {
		b.WriteString(body)
		b.WriteString("\n")
	}
	return name, b.String(), true
}

// ADRMarker returns the ADR id a projected file was written for, or false
// when content is not a Polterware projection.
func ADRMarker(content string) (string, bool) {
	m := adrMarker.FindStringSubmatch(content)
	if m == nil {
		return "", false
	}
	return m[1], true
}

// ADRFileNumber returns the four-digit number of a `NNNN-*.md` file name.
func ADRFileNumber(name string) (string, bool) {
	m := adrFileName.FindStringSubmatch(name)
	if m == nil {
		return "", false
	}
	return m[1], true
}

// Block renders the AGENTS.md block for checkout ("" is the project root):
// the nodes placed in it, the decisions that govern it or its nodes, and the
// invariants of those nodes and their ancestors.
func Block(checkout string, nodes []atlas.Node, governed []ADR, adrs []ADR) string {
	applicable := applicableNodes(checkout, nodes)

	var own []string
	for _, node := range applicable {
		if node.Repo != checkout {
			continue
		}
		line := fmt.Sprintf("- %s (%s) %s", node.Path, node.Level, node.Title)
		if node.Folder != "" {
			line += " · path: " + node.Folder
		}
		own = append(own, line)
	}

	decisions := append([]ADR(nil), governed...)
	for _, node := range applicable {
		for _, ref := range node.Decisions {
			for _, adr := range adrs {
				if Cites(ref, adr) && !containsADR(decisions, adr.ID) {
					decisions = append(decisions, adr)
				}
			}
		}
	}
	sortADRs(decisions)

	var invariants []string
	for _, node := range applicable {
		for _, inv := range node.Invariants {
			if inv.State == work.InvariantActive {
				invariants = append(invariants, fmt.Sprintf("- %s (from %s)", inv.Text, node.Path))
			}
		}
	}

	var b strings.Builder
	b.WriteString(BlockBegin + "\n")
	b.WriteString("## Polterware decisions and invariants\n\n")
	b.WriteString("Generated by `polterware export` from the Polterware project store. Edits inside this block are replaced on the next export; change the source with `polterware apply`.\n")
	if len(own)+len(decisions)+len(invariants) == 0 {
		b.WriteString("\nNo Atlas nodes, decisions, or invariants apply to this checkout.\n")
	}
	writeSection(&b, "Nodes", own)
	var decisionLines []string
	for _, adr := range decisions {
		line := "- " + adr.Title
		if adr.Status != "" {
			line += " (" + adr.Status + ")"
		}
		decisionLines = append(decisionLines, line)
	}
	writeSection(&b, "Decisions", decisionLines)
	writeSection(&b, "Invariants", invariants)
	b.WriteString(BlockEnd + "\n")
	return b.String()
}

// ReplaceBlock puts block into an AGENTS.md body. An existing block is
// replaced in place; otherwise the block is appended. A begin sentinel
// without its end is an error, so a broken file is never truncated.
func ReplaceBlock(existing, block string) (string, error) {
	begin := strings.Index(existing, BlockBegin)
	if begin < 0 {
		if strings.TrimSpace(existing) == "" {
			return block, nil
		}
		return strings.TrimRight(existing, "\n") + "\n\n" + block, nil
	}
	rest := existing[begin:]
	end := strings.Index(rest, BlockEnd)
	if end < 0 {
		return "", fmt.Errorf("%s has %q without %q: fix the file by hand", AgentsFile, BlockBegin, BlockEnd)
	}
	after := rest[end+len(BlockEnd):]
	after = strings.TrimPrefix(after, "\n")
	return existing[:begin] + block + after, nil
}

// applicableNodes returns active nodes placed in checkout plus their active
// ancestors, in graph order, so inherited invariants reach every checkout.
func applicableNodes(checkout string, nodes []atlas.Node) []atlas.Node {
	byID := map[string]atlas.Node{}
	for _, node := range nodes {
		byID[node.ID] = node
	}
	keep := map[string]bool{}
	for _, node := range nodes {
		if node.Status == atlas.NodeRemoved || node.Repo != checkout {
			continue
		}
		keep[node.ID] = true
		for parent, ok := byID[node.ParentID]; ok && parent.Status != atlas.NodeRemoved; parent, ok = byID[parent.ParentID] {
			keep[parent.ID] = true
		}
	}
	var out []atlas.Node
	for _, node := range nodes {
		if keep[node.ID] {
			out = append(out, node)
		}
	}
	return out
}

func writeSection(b *strings.Builder, title string, lines []string) {
	if len(lines) == 0 {
		return
	}
	fmt.Fprintf(b, "\n%s:\n", title)
	for _, line := range lines {
		b.WriteString(line)
		b.WriteString("\n")
	}
}

func containsADR(list []ADR, id string) bool {
	return slices.ContainsFunc(list, func(adr ADR) bool { return adr.ID == id })
}

// sortADRs orders by ADR number, then title; unnumbered records go last.
func sortADRs(list []ADR) {
	slices.SortStableFunc(list, func(a, b ADR) int {
		na, oka := polter.ParseADRNumber(a.Title)
		nb, okb := polter.ParseADRNumber(b.Title)
		switch {
		case oka && okb && na != nb:
			return na - nb
		case oka != okb:
			if oka {
				return -1
			}
			return 1
		}
		return strings.Compare(a.Title, b.Title)
	})
}

func slugify(title string) string {
	slug := strings.ReplaceAll(work.NormalizeText(title), " ", "-")
	runes := []rune(slug)
	if len(runes) > maxSlugRunes {
		slug = strings.TrimRight(string(runes[:maxSlugRunes]), "-")
	}
	return slug
}
