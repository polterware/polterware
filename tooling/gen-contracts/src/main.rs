//! Generates the Desktop's contracts (`app/src/contracts`) from the Protobuf schemas: one serde
//! struct per message in the proto3 JSON mapping the core speaks over Connect-JSON, and one client
//! per service on `crate::client::Core`. It reads the FileDescriptorSet that
//! `buf build -o <file>#format=json` writes and supports only what the schemas use (scalars,
//! messages, repeated fields, string maps, proto3 `optional`, unary and server-streaming
//! methods). Anything else stops it with an error rather than producing a wrong mapping.
//!
//! `--client <path>` puts the services on another client than the core's, such as Polterware
//! Dispatch's (`crate::dispatch::Dispatch`), which offers the same `unary` and `server_stream`.
//!
//!   cargo run -p gen-contracts -- <descriptor.json> <out dir> [--client <path>] [--check]

use std::collections::{BTreeMap, HashMap, HashSet};
use std::io::Write;
use std::path::Path;
use std::process::{Command, Stdio};

use serde_json::Value;

const HEADER: &str = "// Code generated by tooling/gen-contracts from schemas/. DO NOT EDIT.\n";

const RUST_KEYWORDS: &[&str] = &[
    "as", "async", "await", "break", "const", "continue", "dyn", "else", "enum", "extern", "false",
    "fn", "for", "gen", "if", "impl", "in", "let", "loop", "match", "mod", "move", "mut", "pub",
    "ref", "return", "static", "struct", "trait", "true", "type", "unsafe", "use", "where",
    "while", "abstract", "become", "box", "do", "final", "macro", "override", "priv", "try",
    "typeof", "unsized", "virtual", "yield",
];
const NOT_RAW: &[&str] = &["self", "Self", "super", "crate"];

fn fail(message: impl std::fmt::Display) -> ! {
    eprintln!("gen-contracts: {message}");
    std::process::exit(1);
}

fn usage() -> ! {
    eprintln!("usage: gen-contracts <descriptor.json> <out dir> [--client <path>] [--check]");
    std::process::exit(2);
}

fn field_ident(name: &str) -> String {
    if NOT_RAW.contains(&name) {
        format!("{name}_")
    } else if RUST_KEYWORDS.contains(&name) {
        format!("r#{name}")
    } else {
        name.to_string()
    }
}

/// `ListInbox` -> `list_inbox`, `HTTPServer` -> `http_server`.
fn snake(name: &str) -> String {
    let chars: Vec<char> = name.chars().collect();
    let mut first = Vec::with_capacity(chars.len() + 4);
    let mut i = 0;
    while i < chars.len() {
        let c = chars[i];
        first.push(c);
        if (c.is_ascii_lowercase() || c.is_ascii_digit())
            && chars.get(i + 1).is_some_and(|n| n.is_ascii_uppercase())
        {
            first.push('_');
            first.push(chars[i + 1]);
            i += 2;
        } else {
            i += 1;
        }
    }
    let mut out = String::with_capacity(first.len() + 4);
    let mut i = 0;
    while i < first.len() {
        let c = first[i];
        if c.is_ascii_uppercase()
            && first.get(i + 1).is_some_and(|n| n.is_ascii_uppercase())
            && first.get(i + 2).is_some_and(|n| n.is_ascii_lowercase())
        {
            out.push(c);
            out.push('_');
            out.push(first[i + 1]);
            out.push(first[i + 2]);
            i += 3;
        } else {
            out.push(c);
            i += 1;
        }
    }
    out.to_lowercase()
}

/// `polterware.local.v1` -> `local_v1`.
fn module_of(pkg: &str) -> String {
    pkg.split('.').skip(1).collect::<Vec<_>>().join("_")
}

/// The order names sort in: letters ignoring case first, as a locale compare does.
fn name_order(a: &str, b: &str) -> std::cmp::Ordering {
    a.to_lowercase()
        .cmp(&b.to_lowercase())
        .then_with(|| a.cmp(b))
}

fn str_of<'a>(value: &'a Value, key: &str) -> &'a str {
    value.get(key).and_then(Value::as_str).unwrap_or("")
}

fn list<'a>(value: &'a Value, key: &str) -> &'a [Value] {
    value
        .get(key)
        .and_then(Value::as_array)
        .map(Vec::as_slice)
        .unwrap_or(&[])
}

fn is_map_entry(message: &Value) -> bool {
    message
        .get("options")
        .and_then(|o| o.get("mapEntry"))
        .and_then(Value::as_bool)
        .unwrap_or(false)
}

fn repeated(field: &Value) -> bool {
    str_of(field, "label") == "LABEL_REPEATED"
}

fn proto3_optional(field: &Value) -> bool {
    field
        .get("proto3Optional")
        .and_then(Value::as_bool)
        .unwrap_or(false)
}

fn comments(file: &Value, path: &[i64]) -> Vec<String> {
    let locations = file
        .get("sourceCodeInfo")
        .map(|info| list(info, "location"))
        .unwrap_or(&[]);
    let location = locations.iter().find(|entry| {
        let parts = list(entry, "path");
        !parts.is_empty()
            && parts.len() == path.len()
            && parts.iter().zip(path).all(|(a, b)| a.as_i64() == Some(*b))
    });
    let Some(text) = location
        .and_then(|l| l.get("leadingComments"))
        .and_then(Value::as_str)
        .filter(|t| !t.is_empty())
    else {
        return Vec::new();
    };
    let text = text.strip_suffix('\n').unwrap_or(text);
    text.split('\n')
        .map(|line| {
            line.strip_prefix(' ')
                .unwrap_or(line)
                .trim_end()
                .to_string()
        })
        .collect()
}

fn doc_lines(lines: &[String], indent: &str) -> String {
    lines
        .iter()
        .map(|line| {
            if line.is_empty() {
                format!("{indent}///")
            } else {
                format!("{indent}/// {line}")
            }
        })
        .collect::<Vec<_>>()
        .join("\n")
}

fn with_doc(doc: &str) -> String {
    if doc.is_empty() {
        String::new()
    } else {
        format!("{doc}\n")
    }
}

struct Message<'a> {
    message: &'a Value,
    pkg: String,
}

struct Generator<'a> {
    messages: HashMap<String, Message<'a>>,
    /// Every message's full name in descriptor order.
    order: Vec<String>,
    float_memo: HashMap<String, bool>,
}

impl<'a> Generator<'a> {
    fn new(files: &'a [Value]) -> Self {
        let names: HashSet<&str> = files.iter().map(|f| str_of(f, "name")).collect();
        let mut messages = HashMap::new();
        let mut order = Vec::new();
        for file in files {
            let file_name = str_of(file, "name");
            if !list(file, "enumType").is_empty() {
                fail(format!("{file_name}: enums are not supported"));
            }
            for dependency in list(file, "dependency") {
                let dependency = dependency.as_str().unwrap_or("");
                if !names.contains(dependency) {
                    fail(format!("{file_name}: import {dependency} is not supported"));
                }
            }
            let pkg = str_of(file, "package").to_string();
            for message in list(file, "messageType") {
                let full = format!(".{pkg}.{}", str_of(message, "name"));
                order.push(full.clone());
                messages.insert(
                    full,
                    Message {
                        message,
                        pkg: pkg.clone(),
                    },
                );
            }
        }
        Self {
            messages,
            order,
            float_memo: HashMap::new(),
        }
    }

    fn get(&self, type_name: &str) -> &Message<'a> {
        self.messages
            .get(type_name)
            .unwrap_or_else(|| fail(format!("unknown message {type_name}")))
    }

    fn rust_path(&self, type_name: &str, from_pkg: &str) -> String {
        let target = self.get(type_name);
        let name = str_of(target.message, "name");
        if target.pkg == from_pkg {
            name.to_string()
        } else {
            format!("super::{}::{name}", module_of(&target.pkg))
        }
    }

    /// Singular message fields hold their value inline, so a message that reaches itself through
    /// them needs a Box somewhere on the cycle. The schemas have none today; this keeps it so.
    fn check_no_inline_cycle(&self) {
        let edges: HashMap<&str, Vec<&str>> = self
            .order
            .iter()
            .map(|name| {
                let message = self.messages[name].message;
                let next = list(message, "field")
                    .iter()
                    .filter(|f| str_of(f, "type") == "TYPE_MESSAGE" && !repeated(f))
                    .map(|f| str_of(f, "typeName"))
                    .collect();
                (name.as_str(), next)
            })
            .collect();
        #[derive(PartialEq)]
        enum State {
            Open,
            Done,
        }
        fn visit<'n>(
            name: &'n str,
            trail: &mut Vec<&'n str>,
            edges: &HashMap<&'n str, Vec<&'n str>>,
            state: &mut HashMap<&'n str, State>,
        ) {
            match state.get(name) {
                Some(State::Done) => return,
                Some(State::Open) => {
                    trail.push(name);
                    fail(format!(
                        "recursive message {} needs a Box",
                        trail.join(" -> ")
                    ));
                }
                None => {}
            }
            state.insert(name, State::Open);
            trail.push(name);
            for next in edges.get(name).map(Vec::as_slice).unwrap_or(&[]) {
                visit(next, trail, edges, state);
            }
            trail.pop();
            state.insert(name, State::Done);
        }
        let mut state = HashMap::new();
        for name in &self.order {
            visit(name, &mut Vec::new(), &edges, &mut state);
        }
    }

    /// `Eq` derives only where no `f64` is reachable, through any field.
    fn reaches_float(&mut self, name: &str) -> bool {
        if let Some(&known) = self.float_memo.get(name) {
            return known;
        }
        self.float_memo.insert(name.to_string(), false);
        let message = self.get(name).message;
        let mut result = false;
        for field in list(message, "field") {
            let hit = if str_of(field, "type") != "TYPE_MESSAGE" {
                str_of(field, "type") == "TYPE_DOUBLE"
            } else if let Some(entry) = map_entry(message, str_of(field, "typeName")) {
                let mut any = false;
                for part in list(entry, "field") {
                    let part_hit = if str_of(part, "type") == "TYPE_MESSAGE" {
                        self.reaches_float(str_of(part, "typeName"))
                    } else {
                        str_of(part, "type") == "TYPE_DOUBLE"
                    };
                    any |= part_hit;
                }
                any
            } else {
                self.reaches_float(str_of(field, "typeName"))
            };
            result |= hit;
        }
        self.float_memo.insert(name.to_string(), result);
        result
    }

    fn field_code(
        &self,
        file: &Value,
        message: &Value,
        message_index: usize,
        field: &Value,
        field_index: usize,
    ) -> String {
        let pkg = str_of(file, "package");
        let field_name = str_of(field, "name");
        let ty = str_of(field, "type");
        let place = format!("{}.{field_name}", str_of(message, "name"));
        let mut attrs: Vec<String> = Vec::new();
        let json_name = str_of(field, "jsonName");
        if !json_name.is_empty() && json_name != field_name {
            attrs.push(format!("rename = \"{json_name}\""));
        }
        if field.get("oneofIndex").is_some() && !proto3_optional(field) {
            fail(format!("{place}: oneof is not supported"));
        }
        let rust_type = if repeated(field) {
            let entry = (ty == "TYPE_MESSAGE")
                .then(|| map_entry(message, str_of(field, "typeName")))
                .flatten();
            if let Some(entry) = entry {
                let parts = list(entry, "field");
                let (key, value) = (&parts[0], &parts[1]);
                if str_of(key, "type") != "TYPE_STRING" {
                    fail(format!("{place}: only string map keys are supported"));
                }
                let value_type = match str_of(value, "type") {
                    "TYPE_MESSAGE" => self.rust_path(str_of(value, "typeName"), pkg),
                    "TYPE_STRING" => "String".to_string(),
                    other => fail(format!("{place}: map values of {other} are not supported")),
                };
                format!("BTreeMap<String, {value_type}>")
            } else if ty == "TYPE_MESSAGE" {
                format!("Vec<{}>", self.rust_path(str_of(field, "typeName"), pkg))
            } else if matches!(
                ty,
                "TYPE_STRING" | "TYPE_BOOL" | "TYPE_INT32" | "TYPE_DOUBLE"
            ) {
                format!("Vec<{}>", scalar(ty).unwrap())
            } else {
                fail(format!("{place}: repeated {ty} is not supported"))
            }
        } else if ty == "TYPE_MESSAGE" {
            if map_entry(message, str_of(field, "typeName")).is_some() {
                fail(format!("{place}: unexpected map entry"));
            }
            attrs.push("skip_serializing_if = \"Option::is_none\"".into());
            format!("Option<{}>", self.rust_path(str_of(field, "typeName"), pkg))
        } else if let Some(scalar) = scalar(ty) {
            if proto3_optional(field) {
                if ty == "TYPE_BYTES" {
                    fail(format!("{place}: optional {ty} is not supported"));
                }
                attrs.push("skip_serializing_if = \"Option::is_none\"".into());
                if ty == "TYPE_INT64" {
                    attrs.push("with = \"crate::proto_json::optional_int64\"".into());
                }
                format!("Option<{scalar}>")
            } else {
                match ty {
                    "TYPE_INT64" => attrs.push("with = \"crate::proto_json::int64\"".into()),
                    "TYPE_BYTES" => attrs.push("with = \"crate::proto_json::bytes\"".into()),
                    "TYPE_DOUBLE" => {
                        attrs.push("deserialize_with = \"crate::proto_json::double\"".into())
                    }
                    _ => {}
                }
                scalar.to_string()
            }
        } else {
            fail(format!("{place}: {ty} is not supported"))
        };
        let doc = doc_lines(
            &comments(file, &[4, message_index as i64, 2, field_index as i64]),
            "    ",
        );
        let attr = if attrs.is_empty() {
            String::new()
        } else {
            format!("    #[serde({})]\n", attrs.join(", "))
        };
        format!(
            "{}{attr}    pub {}: {rust_type},",
            with_doc(&doc),
            field_ident(field_name)
        )
    }

    fn message_code(&mut self, file: &Value, message: &Value, index: usize) -> String {
        let name = str_of(message, "name");
        for nested in list(message, "nestedType") {
            if !is_map_entry(nested) {
                fail(format!(
                    "{name}.{}: nested messages are not supported",
                    str_of(nested, "name")
                ));
            }
        }
        if !list(message, "enumType").is_empty() {
            fail(format!("{name}: nested enums are not supported"));
        }
        let doc = doc_lines(&comments(file, &[4, index as i64]), "");
        let fields: Vec<String> = list(message, "field")
            .iter()
            .enumerate()
            .map(|(i, field)| self.field_code(file, message, index, field, i))
            .collect();
        let full = format!(".{}.{name}", str_of(file, "package"));
        let derives = if self.reaches_float(&full) {
            "Clone, Debug, Default, PartialEq, Serialize, Deserialize"
        } else {
            "Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize"
        };
        let body = if fields.is_empty() {
            String::new()
        } else {
            format!("\n{}\n", fields.join("\n"))
        };
        format!(
            "{}#[derive({derives})]\n#[serde(default)]\npub struct {name} {{{body}}}\n",
            with_doc(&doc)
        )
    }
}

fn map_entry<'v>(message: &'v Value, type_name: &str) -> Option<&'v Value> {
    let nested_name = type_name.rsplit('.').next().unwrap_or("");
    list(message, "nestedType")
        .iter()
        .find(|entry| str_of(entry, "name") == nested_name)
        .filter(|entry| is_map_entry(entry))
}

fn scalar(ty: &str) -> Option<&'static str> {
    Some(match ty {
        "TYPE_STRING" => "String",
        "TYPE_BOOL" => "bool",
        "TYPE_INT32" => "i32",
        "TYPE_INT64" => "i64",
        "TYPE_DOUBLE" => "f64",
        "TYPE_BYTES" => "Vec<u8>",
        _ => return None,
    })
}

fn valid_client_path(path: &str) -> bool {
    let mut parts = path.split("::");
    if parts.next() != Some("crate") {
        return false;
    }
    let rest: Vec<&str> = parts.collect();
    !rest.is_empty()
        && rest.iter().all(|part| {
            let mut chars = part.chars();
            chars
                .next()
                .is_some_and(|c| c.is_ascii_alphabetic() || c == '_')
                && chars.all(|c| c.is_ascii_alphanumeric() || c == '_')
        })
}

/// The files go through rustfmt so `cargo fmt --check` holds for them as for the rest.
fn rustfmt(code: &str) -> String {
    let mut child = Command::new("rustfmt")
        .args(["--edition", "2024", "--emit", "stdout", "--quiet"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::piped())
        .spawn()
        .unwrap_or_else(|error| fail(format!("rustfmt: {error}")));
    let mut stdin = child.stdin.take().unwrap();
    let input = code.to_string();
    let writer = std::thread::spawn(move || stdin.write_all(input.as_bytes()));
    let output = child
        .wait_with_output()
        .unwrap_or_else(|error| fail(format!("rustfmt: {error}")));
    writer
        .join()
        .unwrap()
        .unwrap_or_else(|error| fail(format!("rustfmt: {error}")));
    if !output.status.success() {
        fail(format!(
            "rustfmt: {}",
            String::from_utf8_lossy(&output.stderr)
        ));
    }
    String::from_utf8(output.stdout).unwrap_or_else(|error| fail(format!("rustfmt: {error}")))
}

fn main() {
    let args: Vec<String> = std::env::args().skip(1).collect();
    if args.len() < 2 {
        usage();
    }
    let (descriptor_path, out_dir) = (&args[0], Path::new(&args[1]));
    let flags = &args[2..];
    let check = flags.iter().any(|f| f == "--check");
    let client_path = match flags.iter().position(|f| f == "--client") {
        Some(i) => flags.get(i + 1).cloned().unwrap_or_default(),
        None => "crate::client::Core".to_string(),
    };
    if !valid_client_path(&client_path) {
        eprintln!("gen-contracts: --client takes a path such as crate::dispatch::Dispatch");
        std::process::exit(2);
    }
    let client_type = client_path.rsplit("::").next().unwrap().to_string();
    let text = std::fs::read_to_string(descriptor_path)
        .unwrap_or_else(|error| fail(format!("{descriptor_path}: {error}")));
    let set: Value = serde_json::from_str(&text)
        .unwrap_or_else(|error| fail(format!("{descriptor_path}: {error}")));
    let files = list(&set, "file");

    let mut generator = Generator::new(files);
    generator.check_no_inline_cycle();

    // One module per package, its files in name order.
    let mut sorted: Vec<&Value> = files.iter().collect();
    sorted.sort_by(|a, b| name_order(str_of(a, "name"), str_of(b, "name")));
    let mut packages: Vec<(String, Vec<&Value>)> = Vec::new();
    for file in sorted {
        let pkg = str_of(file, "package").to_string();
        match packages.iter_mut().find(|(p, _)| *p == pkg) {
            Some((_, list)) => list.push(file),
            None => packages.push((pkg, vec![file])),
        }
    }

    let mut outputs: Vec<(String, String)> = Vec::new();
    for (pkg, pkg_files) in &packages {
        let mut parts = Vec::new();
        for file in pkg_files {
            let items: Vec<String> = list(file, "messageType")
                .iter()
                .enumerate()
                .map(|(i, message)| generator.message_code(file, message, i))
                .collect();
            if !items.is_empty() {
                parts.push(format!(
                    "// {}\n\n{}",
                    str_of(file, "name"),
                    items.join("\n")
                ));
            }
        }
        let all = parts.join("\n");
        let mut imports = vec!["use serde::{Deserialize, Serialize};".to_string()];
        if all.contains("BTreeMap<") {
            imports.insert(0, "use std::collections::BTreeMap;\n".into());
        }
        outputs.push((
            format!("{}.rs", module_of(pkg)),
            format!(
                "{HEADER}//! Messages of `{pkg}` in the proto3 JSON mapping.\n\n{}\n\n{all}",
                imports.join("\n")
            ),
        ));
    }

    // Services: `core.work().list_inbox(&request)`.
    let mut services: Vec<(&Value, &Value, usize)> = Vec::new();
    for file in files {
        for (i, service) in list(file, "service").iter().enumerate() {
            services.push((file, service, i));
        }
    }
    services.sort_by(|a, b| name_order(str_of(a.1, "name"), str_of(b.1, "name")));
    let mut accessors = Vec::new();
    let mut clients = Vec::new();
    // The request and response types the clients name, imported by name from their modules.
    let mut used: BTreeMap<String, String> = BTreeMap::new();
    let mut use_type = |type_name: &str| -> String {
        let target = generator.get(type_name);
        let name = str_of(target.message, "name").to_string();
        if let Some(previous) = used.get(&name)
            && *previous != target.pkg
        {
            fail(format!(
                "{name} is defined in both {previous} and {}",
                target.pkg
            ));
        }
        used.insert(name.clone(), target.pkg.clone());
        name
    };
    for (file, service, service_index) in &services {
        let pkg = str_of(file, "package");
        let service_name = str_of(service, "name");
        let accessor = snake(service_name.strip_suffix("Service").unwrap_or(service_name));
        let service_doc = comments(file, &[6, *service_index as i64]);
        accessors.push(format!(
            "    /// `{pkg}.{service_name}`.\n    pub fn {accessor}(&self) -> {service_name}<'_> {{\n        {service_name}(self)\n    }}"
        ));
        let mut methods = Vec::new();
        for (method_index, method) in list(service, "method").iter().enumerate() {
            let method_name = str_of(method, "name");
            let flag = |key: &str| method.get(key).and_then(Value::as_bool).unwrap_or(false);
            if flag("clientStreaming") {
                fail(format!(
                    "{service_name}.{method_name}: client streaming is not supported"
                ));
            }
            let input = use_type(str_of(method, "inputType"));
            let output = use_type(str_of(method, "outputType"));
            let route = format!("{pkg}.{service_name}/{method_name}");
            let doc = doc_lines(
                &comments(file, &[6, *service_index as i64, 2, method_index as i64]),
                "    ",
            );
            let name = field_ident(&snake(method_name));
            methods.push(if flag("serverStreaming") {
                format!(
                    "{}    pub fn {name}(&self, request: &{input}) -> Result<ServerStream<{output}>, CoreError> {{\n        self.0.server_stream(\"{route}\", request)\n    }}",
                    with_doc(&doc)
                )
            } else {
                format!(
                    "{}    pub fn {name}(&self, request: &{input}) -> Result<{output}, CoreError> {{\n        self.0.unary(\"{route}\", request)\n    }}",
                    with_doc(&doc)
                )
            });
        }
        let doc = if service_doc.is_empty() {
            vec![format!("`{pkg}.{service_name}`.")]
        } else {
            service_doc
        };
        clients.push(format!(
            "{}\npub struct {service_name}<'a>(&'a {client_type});\n\nimpl {service_name}<'_> {{\n{}\n}}\n",
            doc_lines(&doc, ""),
            methods.join("\n\n")
        ));
    }
    let mut used: Vec<(String, String)> = used.into_iter().collect();
    used.sort_by(|a, b| name_order(&a.0, &b.0));
    let mut imports_by_module: Vec<(String, Vec<String>)> = Vec::new();
    for (name, pkg) in used {
        let module = module_of(&pkg);
        match imports_by_module.iter_mut().find(|(m, _)| *m == module) {
            Some((_, names)) => names.push(name),
            None => imports_by_module.push((module, vec![name])),
        }
    }
    imports_by_module.sort_by(|a, b| name_order(&a.0, &b.0));
    let type_imports = imports_by_module
        .iter()
        .map(|(module, names)| format!("use super::{module}::{{{}}};", names.join(", ")))
        .collect::<Vec<_>>()
        .join("\n");
    let reach = if client_type == "Core" {
        ": `core.work().list_inbox(&request)`"
    } else {
        ""
    };
    let client_use = if client_path == "crate::client::Core" {
        "use crate::client::{Core, CoreError, ServerStream};\n\n".to_string()
    } else {
        format!("use crate::client::{{CoreError, ServerStream}};\nuse {client_path};\n\n")
    };
    outputs.push((
        "services.rs".into(),
        format!(
            "{HEADER}//! A client per core service, reached from [`{client_type}`]{reach}.\n\n{client_use}{type_imports}\n\nimpl {client_type} {{\n{}\n}}\n\n{}",
            accessors.join("\n\n"),
            clients.join("\n")
        ),
    ));

    // Every message is also re-exported at the top (`contracts::ListInboxRequest`), so two
    // packages may not name a message the same.
    let mut owners: HashMap<&str, &str> = HashMap::new();
    for name in &generator.order {
        let target = &generator.messages[name];
        let message_name = str_of(target.message, "name");
        if let Some(owner) = owners.get(message_name)
            && *owner != target.pkg
        {
            fail(format!(
                "{message_name} is defined in both {owner} and {}",
                target.pkg
            ));
        }
        owners.insert(message_name, &target.pkg);
    }
    let modules: Vec<String> = packages.iter().map(|(pkg, _)| module_of(pkg)).collect();
    outputs.push((
        "mod.rs".into(),
        format!(
            "{HEADER}//! The core's contracts, generated from `schemas/` (`tooling/gen-contracts`).\n\n#![allow(clippy::doc_lazy_continuation, clippy::doc_overindented_list_items)]\n\n{}\nmod services;\n\n{}\npub use services::*;\n",
            modules
                .iter()
                .map(|m| format!("pub mod {m};"))
                .collect::<Vec<_>>()
                .join("\n"),
            modules
                .iter()
                .map(|m| format!("pub use {m}::*;"))
                .collect::<Vec<_>>()
                .join("\n"),
        ),
    ));

    let mut stale = Vec::new();
    if !check {
        std::fs::create_dir_all(out_dir).unwrap_or_else(|error| fail(error));
    }
    for (name, code) in &outputs {
        let target = out_dir.join(name);
        let content = rustfmt(code);
        if check {
            if std::fs::read_to_string(&target).ok().as_deref() != Some(content.as_str()) {
                stale.push(name.clone());
            }
        } else {
            std::fs::write(&target, content).unwrap_or_else(|error| fail(error));
        }
    }
    if let Ok(entries) = std::fs::read_dir(out_dir) {
        let mut names: Vec<String> = entries
            .filter_map(Result::ok)
            .map(|e| e.file_name().to_string_lossy().into_owned())
            .collect();
        names.sort();
        for name in names {
            if name.ends_with(".rs") && !outputs.iter().any(|(n, _)| *n == name) {
                if check {
                    stale.push(format!("{name} (no longer generated)"));
                } else {
                    fail(format!(
                        "{} is not generated; remove it by hand",
                        out_dir.join(&name).display()
                    ));
                }
            }
        }
    }
    if !stale.is_empty() {
        fail(format!(
            "out of date: {}; run bash tooling/generate.sh",
            stale.join(", ")
        ));
    }
}
