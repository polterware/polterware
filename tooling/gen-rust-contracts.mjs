#!/usr/bin/env node
// Generates the GPUI Desktop's contracts (desktop-gpui/src/contracts) from the Protobuf schemas: one
// serde struct per message in the proto3 JSON mapping the core speaks over Connect-JSON, and one
// client per service on `crate::client::Core`. It reads the FileDescriptorSet that
// `buf build -o <file>#format=json` writes and supports only what the schemas use (scalars,
// messages, repeated fields, string maps, proto3 `optional`, unary and server-streaming
// methods). Anything else stops it with an error rather than producing a wrong mapping.
//
// `--client <path>` puts the services on another client than the core's, such as Polterware
// Dispatch's (`crate::dispatch::Dispatch`), which offers the same `unary` and `server_stream`.
//
//   node tooling/gen-rust-contracts.mjs <descriptor.json> <out dir> [--client <path>] [--check]
import { execFileSync } from "node:child_process";
import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";

const [descriptorPath, outDir, ...flags] = process.argv.slice(2);
if (!descriptorPath || !outDir) {
  console.error("usage: gen-rust-contracts.mjs <descriptor.json> <out dir> [--client <path>] [--check]");
  process.exit(2);
}
const check = flags.includes("--check");
const clientFlag = flags.indexOf("--client");
const clientPath = clientFlag >= 0 ? flags[clientFlag + 1] : "crate::client::Core";
if (!clientPath || !/^crate(::[A-Za-z_][A-Za-z0-9_]*)+$/.test(clientPath)) {
  console.error("gen-rust-contracts: --client takes a path such as crate::dispatch::Dispatch");
  process.exit(2);
}
const clientType = clientPath.split("::").pop();
const set = JSON.parse(readFileSync(descriptorPath, "utf8"));
const HEADER = "// Code generated by tooling/gen-rust-contracts.mjs from schemas/. DO NOT EDIT.\n";

const fail = (message) => {
  console.error(`gen-rust-contracts: ${message}`);
  process.exit(1);
};

const RUST_KEYWORDS = new Set(
  (
    "as async await break const continue dyn else enum extern false fn for gen if impl in let " +
    "loop match mod move mut pub ref return static struct trait true type unsafe use where while " +
    "abstract become box do final macro override priv try typeof unsized virtual yield"
  ).split(" "),
);
const NOT_RAW = new Set(["self", "Self", "super", "crate"]);

function fieldIdent(name) {
  if (NOT_RAW.has(name)) return `${name}_`;
  return RUST_KEYWORDS.has(name) ? `r#${name}` : name;
}

function snake(name) {
  return name
    .replace(/([a-z0-9])([A-Z])/g, "$1_$2")
    .replace(/([A-Z])([A-Z][a-z])/g, "$1_$2")
    .toLowerCase();
}

const moduleOf = (pkg) => pkg.split(".").slice(1).join("_"); // polterware.local.v1 -> local_v1

// Every message by its full name (".polterware.local.v1.Card"), with its package and file.
const messages = new Map();
for (const file of set.file) {
  if ((file.enumType ?? []).length) fail(`${file.name}: enums are not supported`);
  for (const dependency of file.dependency ?? []) {
    if (!set.file.some((other) => other.name === dependency)) fail(`${file.name}: import ${dependency} is not supported`);
  }
  (file.messageType ?? []).forEach((message, index) => {
    messages.set(`.${file.package}.${message.name}`, { message, file, index, pkg: file.package });
  });
}

function comments(file, pathParts) {
  const location = (file.sourceCodeInfo?.location ?? []).find(
    (entry) => entry.path && entry.path.length === pathParts.length && entry.path.every((part, i) => part === pathParts[i]),
  );
  const text = location?.leadingComments;
  if (!text) return [];
  const lines = text.replace(/\n$/, "").split("\n").map((line) => line.replace(/^ /, "").replace(/\s+$/, ""));
  return lines;
}

function docLines(lines, indent) {
  return lines.map((line) => (line ? `${indent}/// ${line}` : `${indent}///`)).join("\n");
}

function mapEntry(message, typeName) {
  const nestedName = typeName.split(".").pop();
  const nested = (message.nestedType ?? []).find((entry) => entry.name === nestedName);
  return nested?.options?.mapEntry ? nested : undefined;
}

function rustPath(typeName, fromPkg) {
  const target = messages.get(typeName);
  if (!target) fail(`unknown message ${typeName}`);
  return target.pkg === fromPkg ? target.message.name : `super::${moduleOf(target.pkg)}::${target.message.name}`;
}

// Singular message fields hold their value inline, so a message that reaches itself through them
// needs a Box somewhere on the cycle. The schemas have none today; this keeps it that way.
function checkNoInlineCycle() {
  const edges = new Map();
  for (const [name, { message }] of messages) {
    edges.set(
      name,
      (message.field ?? [])
        .filter((field) => field.type === "TYPE_MESSAGE" && field.label !== "LABEL_REPEATED")
        .map((field) => field.typeName),
    );
  }
  const state = new Map();
  const visit = (name, trail) => {
    if (state.get(name) === "done") return;
    if (state.get(name) === "open") fail(`recursive message ${[...trail, name].join(" -> ")} needs a Box`);
    state.set(name, "open");
    for (const next of edges.get(name) ?? []) visit(next, [...trail, name]);
    state.set(name, "done");
  };
  for (const name of messages.keys()) visit(name, []);
}
checkNoInlineCycle();

// `Eq` derives only where no `f64` is reachable, through any field.
const floatMemo = new Map();
function reachesFloat(name) {
  if (floatMemo.has(name)) return floatMemo.get(name);
  floatMemo.set(name, false);
  const { message } = messages.get(name);
  const fieldTypes = (message.field ?? []).flatMap((field) => {
    if (field.type !== "TYPE_MESSAGE") return [field.type === "TYPE_DOUBLE"];
    const entry = mapEntry(message, field.typeName);
    if (entry) return entry.field.map((part) => (part.type === "TYPE_MESSAGE" ? reachesFloat(part.typeName) : part.type === "TYPE_DOUBLE"));
    return [reachesFloat(field.typeName)];
  });
  const result = fieldTypes.some(Boolean);
  floatMemo.set(name, result);
  return result;
}

const SCALARS = {
  TYPE_STRING: "String",
  TYPE_BOOL: "bool",
  TYPE_INT32: "i32",
  TYPE_INT64: "i64",
  TYPE_DOUBLE: "f64",
  TYPE_BYTES: "Vec<u8>",
};

function fieldCode(file, message, messageIndex, field, fieldIndex) {
  const pkg = file.package;
  const where = `${message.name}.${field.name}`;
  const attrs = [];
  if (field.jsonName && field.jsonName !== field.name) attrs.push(`rename = "${field.jsonName}"`);
  if (field.oneofIndex !== undefined && !field.proto3Optional) fail(`${where}: oneof is not supported`);
  let type;
  if (field.label === "LABEL_REPEATED") {
    const entry = field.type === "TYPE_MESSAGE" ? mapEntry(message, field.typeName) : undefined;
    if (entry) {
      const [key, value] = entry.field;
      if (key.type !== "TYPE_STRING") fail(`${where}: only string map keys are supported`);
      const valueType =
        value.type === "TYPE_MESSAGE" ? rustPath(value.typeName, pkg) : value.type === "TYPE_STRING" ? "String" : undefined;
      if (!valueType) fail(`${where}: map values of ${value.type} are not supported`);
      type = `BTreeMap<String, ${valueType}>`;
    } else if (field.type === "TYPE_MESSAGE") {
      type = `Vec<${rustPath(field.typeName, pkg)}>`;
    } else if (["TYPE_STRING", "TYPE_BOOL", "TYPE_INT32", "TYPE_DOUBLE"].includes(field.type)) {
      type = `Vec<${SCALARS[field.type]}>`;
    } else {
      fail(`${where}: repeated ${field.type} is not supported`);
    }
  } else if (field.type === "TYPE_MESSAGE") {
    if (mapEntry(message, field.typeName)) fail(`${where}: unexpected map entry`);
    type = `Option<${rustPath(field.typeName, pkg)}>`;
    attrs.push(`skip_serializing_if = "Option::is_none"`);
  } else if (SCALARS[field.type]) {
    const scalar = SCALARS[field.type];
    if (field.proto3Optional) {
      if (field.type === "TYPE_BYTES") fail(`${where}: optional ${field.type} is not supported`);
      type = `Option<${scalar}>`;
      attrs.push(`skip_serializing_if = "Option::is_none"`);
      if (field.type === "TYPE_INT64") attrs.push(`with = "crate::proto_json::optional_int64"`);
    } else {
      type = scalar;
      if (field.type === "TYPE_INT64") attrs.push(`with = "crate::proto_json::int64"`);
      if (field.type === "TYPE_BYTES") attrs.push(`with = "crate::proto_json::bytes"`);
      if (field.type === "TYPE_DOUBLE") attrs.push(`deserialize_with = "crate::proto_json::double"`);
    }
  } else {
    fail(`${where}: ${field.type} is not supported`);
  }
  const doc = docLines(comments(file, [4, messageIndex, 2, fieldIndex]), "    ");
  const attr = attrs.length ? `    #[serde(${attrs.join(", ")})]\n` : "";
  return `${doc ? `${doc}\n` : ""}${attr}    pub ${fieldIdent(field.name)}: ${type},`;
}

function messageCode(file, message, index) {
  for (const nested of message.nestedType ?? []) {
    if (!nested.options?.mapEntry) fail(`${message.name}.${nested.name}: nested messages are not supported`);
  }
  if ((message.enumType ?? []).length) fail(`${message.name}: nested enums are not supported`);
  const doc = docLines(comments(file, [4, index]), "");
  const fields = (message.field ?? []).map((field, fieldIndex) => fieldCode(file, message, index, field, fieldIndex));
  const derives = reachesFloat(`.${file.package}.${message.name}`)
    ? "Clone, Debug, Default, PartialEq, Serialize, Deserialize"
    : "Clone, Debug, Default, PartialEq, Eq, Serialize, Deserialize";
  const body = fields.length ? `\n${fields.join("\n")}\n` : "";
  return `${doc ? `${doc}\n` : ""}#[derive(${derives})]\n#[serde(default)]\npub struct ${message.name} {${body}}\n`;
}

// One module per package, its files in name order.
const packages = new Map();
for (const file of [...set.file].sort((a, b) => a.name.localeCompare(b.name))) {
  if (!packages.has(file.package)) packages.set(file.package, []);
  packages.get(file.package).push(file);
}

const outputs = new Map();
for (const [pkg, files] of packages) {
  const parts = [];
  for (const file of files) {
    const items = (file.messageType ?? []).map((message, index) => messageCode(file, message, index));
    if (items.length) parts.push(`// ${file.name}\n\n${items.join("\n")}`);
  }
  const all = parts.join("\n");
  const imports = ["use serde::{Deserialize, Serialize};"];
  if (all.includes("BTreeMap<")) imports.unshift("use std::collections::BTreeMap;\n");
  outputs.set(
    `${moduleOf(pkg)}.rs`,
    `${HEADER}//! Messages of \`${pkg}\` in the proto3 JSON mapping.\n\n${imports.join("\n")}\n\n${all}`,
  );
}

// Services: `core.work().list_inbox(&request)`.
const services = [];
for (const file of set.file) {
  (file.service ?? []).forEach((service, serviceIndex) => services.push({ file, service, serviceIndex }));
}
services.sort((a, b) => a.service.name.localeCompare(b.service.name));
const accessors = [];
const clients = [];
// The request and response types the clients name, imported by name from their modules.
const used = new Map();
const useType = (typeName) => {
  const { pkg, message } = messages.get(typeName) ?? fail(`unknown message ${typeName}`);
  const previous = used.get(message.name);
  if (previous && previous !== pkg) fail(`${message.name} is defined in both ${previous} and ${pkg}`);
  used.set(message.name, pkg);
  return message.name;
};
for (const { file, service, serviceIndex } of services) {
  const pkg = file.package;
  const accessor = snake(service.name.replace(/Service$/, ""));
  const serviceDoc = comments(file, [6, serviceIndex]);
  accessors.push(
    `    /// \`${pkg}.${service.name}\`.\n    pub fn ${accessor}(&self) -> ${service.name}<'_> {\n        ${service.name}(self)\n    }`,
  );
  const methods = (service.method ?? []).map((method, methodIndex) => {
    if (method.clientStreaming) fail(`${service.name}.${method.name}: client streaming is not supported`);
    const input = useType(method.inputType);
    const output = useType(method.outputType);
    const route = `${pkg}.${service.name}/${method.name}`;
    const doc = docLines(comments(file, [6, serviceIndex, 2, methodIndex]), "    ");
    const name = fieldIdent(snake(method.name));
    if (method.serverStreaming) {
      return `${doc ? `${doc}\n` : ""}    pub fn ${name}(&self, request: &${input}) -> Result<ServerStream<${output}>, CoreError> {\n        self.0.server_stream("${route}", request)\n    }`;
    }
    return `${doc ? `${doc}\n` : ""}    pub fn ${name}(&self, request: &${input}) -> Result<${output}, CoreError> {\n        self.0.unary("${route}", request)\n    }`;
  });
  clients.push(
    `${docLines(serviceDoc.length ? serviceDoc : [`\`${pkg}.${service.name}\`.`], "")}\npub struct ${service.name}<'a>(&'a ${clientType});\n\nimpl ${service.name}<'_> {\n${methods.join("\n\n")}\n}\n`,
  );
}
const importsByModule = new Map();
for (const [name, pkg] of [...used].sort(([a], [b]) => a.localeCompare(b))) {
  const module = moduleOf(pkg);
  if (!importsByModule.has(module)) importsByModule.set(module, []);
  importsByModule.get(module).push(name);
}
const typeImports = [...importsByModule]
  .sort(([a], [b]) => a.localeCompare(b))
  .map(([module, names]) => `use super::${module}::{${names.join(", ")}};`)
  .join("\n");
outputs.set(
  "services.rs",
  `${HEADER}//! A client per core service, reached from [\`${clientType}\`]${
    clientType === "Core" ? ": \`core.work().list_inbox(&request)\`" : ""
  }.\n\n` +
    (clientPath === "crate::client::Core"
      ? `use crate::client::{Core, CoreError, ServerStream};\n\n`
      : `use crate::client::{CoreError, ServerStream};\nuse ${clientPath};\n\n`) +
    `${typeImports}\n\n` +
    `impl ${clientType} {\n${accessors.join("\n\n")}\n}\n\n${clients.join("\n")}`,
);

// Every message is also re-exported at the top (`contracts::ListInboxRequest`), so two packages
// may not name a message the same.
const owners = new Map();
for (const { message, pkg } of messages.values()) {
  if (owners.has(message.name) && owners.get(message.name) !== pkg) {
    fail(`${message.name} is defined in both ${owners.get(message.name)} and ${pkg}`);
  }
  owners.set(message.name, pkg);
}
const modules = [...packages.keys()].map(moduleOf);
outputs.set(
  "mod.rs",
  `${HEADER}//! The core's contracts, generated from \`schemas/\` (\`tooling/gen-rust-contracts.mjs\`).\n\n` +
    `#![allow(clippy::doc_lazy_continuation, clippy::doc_overindented_list_items)]\n\n` +
    modules.map((module) => `pub mod ${module};`).join("\n") +
    `\nmod services;\n\n` +
    modules.map((module) => `pub use ${module}::*;`).join("\n") +
    `\npub use services::*;\n`,
);

// The files go through rustfmt so `cargo fmt --check` holds for them as for the rest.
function rustfmt(code) {
  try {
    return execFileSync("rustfmt", ["--edition", "2024", "--emit", "stdout", "--quiet"], {
      input: code,
      encoding: "utf8",
      maxBuffer: 64 * 1024 * 1024,
    });
  } catch (error) {
    fail(`rustfmt: ${error.stderr || error.message}`);
  }
}

let stale = [];
if (!check) mkdirSync(outDir, { recursive: true });
for (const [name, code] of outputs) {
  const target = path.join(outDir, name);
  const content = rustfmt(code);
  if (check) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== content) stale.push(name);
  } else {
    writeFileSync(target, content);
  }
}
if (existsSync(outDir)) {
  for (const name of readdirSync(outDir)) {
    if (name.endsWith(".rs") && !outputs.has(name)) {
      if (check) stale.push(`${name} (no longer generated)`);
      else fail(`${path.join(outDir, name)} is not generated; remove it by hand`);
    }
  }
}
if (stale.length) fail(`out of date: ${stale.join(", ")}; run bash tooling/generate.sh`);
